FAV_TOKEN = 'vote:3:'
'''Moebooru's favorites search: 'vote:3:bob' = the posts bob favorited. Lynxx's spelling is favorited_by:bob (manifest
syntax.fav, the only one the core routes as favorites): _query_tags sends it as the site's token'''


def _site_tag(tag: str) -> str:
    """favorited_by:bob -> vote:3:bob ('-' kept), any other tag as is"""
    neg = '-' if tag.startswith('-') else ''
    m = re_favorited_by_tag.fullmatch(tag[len(neg):])
    return f'{neg}{FAV_TOKEN}{m.group(1)}' if m else tag


