import html
import re
from typing import Never, final

from bs4 import BeautifulSoup

from lynxx.sdk import DownloaderGelbooru, ModuleCaps, re_favorited_by_tag, re_tags_exclude_rx, re_tags_to_process_rx

__all__ = ('DownloaderGb',)

SITENAME = 'https://gelbooru.com/'
MODULE_ABBR = 'gb'
FILE_NAME_PREFIX = f'{MODULE_ABBR}_'
ITEMS_PER_PAGE = 100  # dapi 'limit' (gelbooru 0.2 sites accept 100 at least)
MAX_SEARCH_DEPTH = 20000 + 1
'''gelbooru.com's DAPI answered 'Too deep! Pull it back some. Holy fuck.' (text, no posts) to 'limit=1&pid=20001' and to
'limit=100&pid=201' (2026-11-21; 1.0.1 had rule34.xxx's 200,099): the site limits the offset, pages of 100 end at pid 199 (offset
19,900), 20,000 posts. The core refuses page numbers for a task of MAX_SEARCH_DEPTH posts or more (download.py _resolve_task_pages), hence
20,000 + 1: a task of 20,000 posts is read whole (the core's refusal of a bigger one says 'can only fetch html for 201 pages',
one page too many). Past that only a single task in the default order without date limits goes on, by id cursor (streaming
pipeline, 'id:<N' / 'id:>N sort:id:asc', both checked that day; _prefer_id_cursor). 'or' groups (one task per alternative here),
sort:, -mindate / -maxdate and -include_parchi use page numbers only: a task of more than 20,000 posts is refused ('too many
results ... Try adding an ID filter'), to be narrowed with id:<N / id:>N'''
FAV_TOKEN = 'fav:'
'''gelbooru.com's favorites metatag ('fav:1': posts favorited by the user with id 1, cheat sheet), usable in the DAPI tags like every
metatag (API docs). Lynxx's spelling is favorited_by:1 (manifest syntax.fav): _consume_custom_module_tags sends it as 'fav:1'.
Pools are the metatag 'pool:2', the same in both: it stays in the DAPI tags as typed'''
re_post_page = re.compile(r'^(?:\?page=post&(?:amp;)?s=list|document\.location=\'\?page=favorites|\?page=pool&(?:amp;)?s=show)&.+?$')
re_post_element = re.compile(r'<post\s*>(.*?)</post\s*>', re.DOTALL)
'''a post with child elements (gelbooru.com, 2026-11-21); a post with attributes is '<post id=".." .../>' '''
re_post_field = re.compile(r'<([A-Za-z_]\w*)(?:\s[^>]*?)?\s*(?:/>|>(.*?)</\1\s*>)', re.DOTALL)
'''a field of such a post: '<score>0</score>', '<title/>' '''


def _attr_value(text: str) -> str:
    """The text of a child element as an attribute value of the item string: entities decoded once, '"' as "'" and line breaks as
    spaces (as DownloaderJsonApi writes its item strings): the core's readers end a value at the first '"'"""
    return ' '.join(html.unescape(text).replace('"', '\'').splitlines()).strip()


def _post_item_string(body: str) -> str:
    """'<id>1</id><tags>a b</tags>..' (the inside of a post with child elements) -> '<post id="1" tags="a b" ..></post>', the form
    DownloaderGelbooru reads (rule34.xxx's posts as the core's html parser writes them back): id first, then every field in the
    site's order (created_at, score, width, height, md5, rating, source, change, parent_id, tags, has_comments, file_url,
    preview_url, sample_url, has_children..). Not parsed as html: '<source>' and '<image>' are void elements there and would lose
    their text. A post without a parent says <parent_id>0</parent_id>, rule34.xxx parent_id="": '0' is left empty (the core would
    look for posts of parent 0 with -include_parchi). '' for a post without a numeric id"""
    fields: dict[str, str] = {}
    for m in re_post_field.finditer(body):
        fields.setdefault(m.group(1).lower(), _attr_value(m.group(2) or ''))
    if not fields.get('id', '').isdigit():
        return ''
    if 'tags' in fields:
        fields['tags'] = ' '.join(fields['tags'].split())
    if fields.get('parent_id') == '0':
        fields['parent_id'] = ''
    return '<post ' + ' '.join(f'{name}="{value}"' for name, value in sorted(fields.items(), key=lambda f: f[0] != 'id')) + '></post>'


def _site_tag(tag: str) -> str:
    """favorited_by:1 -> fav:1 ('-' kept), any other tag as is"""
    neg = '-' if tag.startswith('-') else ''
    m = re_favorited_by_tag.fullmatch(tag[len(neg):])
    return f'{neg}{FAV_TOKEN}{m.group(1)}' if m else tag


@final
class DownloaderGb(DownloaderGelbooru):
    CAPABILITIES = frozenset((ModuleCaps.API_KEY, ModuleCaps.API_KEY_REQUIRED, ModuleCaps.PARENT_CHILD, ModuleCaps.SOURCES, ModuleCaps.DATE_FILTER, ModuleCaps.PREVIEW))

    def __init__(self) -> None:
        super().__init__()

    def _get_min_request_interval(self) -> float:
        return 1.0  # terms allow apps / bots through the API only (API key + user id of the user)

    def _get_id_bounds(self) -> Never:
        raise NotImplementedError

    def _form_item_string_manually(self, *ignored) -> Never:
        raise NotImplementedError

    def _get_re_post_page(self) -> re.Pattern:
        return re_post_page

    def _parses_raw_pages(self) -> bool:
        # search pages reach _get_all_post_tags as bytes: posts with child elements are read from the text (see _post_item_string)
        return True

    def _get_all_post_tags(self, raw_html_page: bytes | BeautifulSoup) -> list:
        if not isinstance(raw_html_page, (bytes, bytearray, str)):
            return super()._get_all_post_tags(raw_html_page)  # an html tree (DownloaderGelbooru's favorites / pool pages, unused here)
        text = raw_html_page.decode('utf-8', 'replace') if isinstance(raw_html_page, (bytes, bytearray)) else raw_html_page
        if posts := re_post_element.findall(text):
            return [h for h in map(_post_item_string, posts) if h]
        # posts with attributes (other answers of the DAPI), an empty page: the tree the core would have parsed for DownloaderGelbooru
        return super()._get_all_post_tags(BeautifulSoup(raw_html_page, 'html.parser'))

    def _get_sitename(self) -> str:
        return SITENAME

    def _get_module_abbr(self) -> str:
        return MODULE_ABBR

    def _get_module_abbr_p(self) -> str:
        return FILE_NAME_PREFIX

    def _get_items_per_page(self) -> int:
        return ITEMS_PER_PAGE

    def _get_max_search_depth(self) -> int:
        return MAX_SEARCH_DEPTH

    def _prefer_id_cursor(self, count: int | None) -> bool:
        # the cursor where page numbers are refused (count >= MAX_SEARCH_DEPTH), DownloaderGelbooru's 'count > depth' would leave
        # a task of exactly MAX_SEARCH_DEPTH posts to page numbers and the core's refusal
        return count is None or count >= self._get_max_search_depth()

    def get_re_tags_to_process(self) -> re.Pattern:
        return re_tags_to_process_rx

    def get_re_tags_to_exclude(self) -> re.Pattern:
        return re_tags_exclude_rx

    def _get_tags_concat_char(self) -> str:
        return '+'

    def _get_idval_equal_seaparator(self) -> str:
        return ':'

    def _extract_comments(self, item_id: str) -> None:
        return  # comments are not collected (capability not declared)

    def _extract_favorite_user(self, fav_user_tags: list[re.Match | None]) -> None:
        # favorites are a DAPI metatag here, not the html favorites pages of DownloaderGelbooru (the terms allow the API only):
        # no favorites user, so the tag stays in the query (see _consume_custom_module_tags) and no html address is built
        self.favorites_search_user = ''

    def _extract_pool_id(self, pool_tags: list[re.Match]) -> None:
        # same for pools: 'pool:N' stays in the DAPI tags, the html pool pages are never read
        self.pool_search_str = ''

    def _consume_custom_module_tags(self, tags: str) -> str:
        # every DAPI address (search, count, id cursor, preview) is built from the task tags through here
        cc = self._get_tags_concat_char()
        return cc.join(_site_tag(t) for t in tags.split(cc)) if tags else tags

    def _split_or_group_into_tasks_always(self) -> bool:
        # gelbooru.com documents 'or' as 'tag1 {tag2 ~ tag3}', which "does not work with meta tags", not the '( a ~ b )' that
        # DownloaderGelbooru sends: one search per alternative (results merged by the core)
        return True

    def _get_api_key(self) -> str:
        # the user's own key only (gelbooru.com answers 401 without one): a run without it stops before the first request
        return f'&api_key={self.api_key.key}&user_id={self.api_key.user_id}' if self.api_key else ''

