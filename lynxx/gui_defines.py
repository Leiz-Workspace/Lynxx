# submenus with changing states
class SubMenus(IntEnum):
    SAVE, LOAD, RESET, OPENFOLDER = 0, 1, 3, 5
    PREFIX, STAGS, SSOURCE, SCOMMENTS, SHASHES, SMODE, EXTEND, DPRESERVE, WNONEMPTY, VERBOSE = 0, 2, 3, 4, 5, 6, 8, 9, 10, 11
    RX, RN, RS, RP, EN, XB, BB = 0, 1, 2, 3, 4, 5, 6
    HEADERS, PROXY, TIMEOUT, RETRIES, APIKEY, DWPROXY, IGNOREPROXY = 0, 1, 2, 3, 4, 5, 6
    DOWNLOAD, CHECKTAGS, DBATCH, CLEARLOG = 0, 1, 3, 5
    QBUILDER, IDLIST, UNTAG, RETAG, SORT, DUPLICATES, AUTOCOMPLETEE, AUTOCOMPLETER = 0, 2, 4, 5, 7, 9, 11, 12
    DFULL, DSKIP, DTOUCH = 0, 1, 2

    def __str__(self) -> str:
        return f'{self.__class__.__name__}.{self.name} ({self.value:d})'


class LynxxMenu:
    def __init__(self, *indecies: SubMenus) -> None:
        self.menu: Menu | None = None
        self.statefuls: set[SubMenus] = set(ind for ind in indecies)

    def __bool__(self) -> bool:
        return bool(self.menu)


menu_items = {
    Menus.FILE: LynxxMenu(SubMenus.SAVE, SubMenus.LOAD, SubMenus.RESET),
    Menus.EDIT: LynxxMenu(SubMenus.PREFIX, SubMenus.STAGS, SubMenus.SSOURCE, SubMenus.SCOMMENTS, SubMenus.SHASHES,
                         SubMenus.SMODE, SubMenus.EXTEND, SubMenus.DPRESERVE, SubMenus.WNONEMPTY, SubMenus.VERBOSE),
    Menus.MODULE: LynxxMenu(SubMenus.RX, SubMenus.RN, SubMenus.RS, SubMenus.RP, SubMenus.EN, SubMenus.XB, SubMenus.BB),
    Menus.CONNECTION: LynxxMenu(SubMenus.HEADERS, SubMenus.PROXY, SubMenus.TIMEOUT, SubMenus.RETRIES, SubMenus.APIKEY, SubMenus.DWPROXY,
                               SubMenus.IGNOREPROXY),
    Menus.ACTIONS: LynxxMenu(SubMenus.DOWNLOAD, SubMenus.CHECKTAGS, SubMenus.DBATCH),
    Menus.TOOLS: LynxxMenu(SubMenus.QBUILDER, SubMenus.IDLIST, SubMenus.UNTAG, SubMenus.RETAG, SubMenus.SORT, SubMenus.DUPLICATES,
                          SubMenus.AUTOCOMPLETEE, SubMenus.AUTOCOMPLETER),
    Menus.DEBUG: LynxxMenu(SubMenus.DFULL, SubMenus.DSKIP, SubMenus.DTOUCH),
}

