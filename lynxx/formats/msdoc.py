"""Word 97-2003 binary documents (.doc / .dot), Kingsoft WPS Writer (.wps) and Microsoft Works (.wps).

Word binary ([MS-DOC]): the FIB at the start of the ``WordDocument`` stream points
at the piece table (CLX) in the ``0Table`` / ``1Table`` stream; every piece maps a
run of character positions (CPs) to 8-bit ("compressed", cp1252) or UTF-16LE text
in the ``WordDocument`` stream. The first ``ccpText`` characters are the main
document. Paragraph properties (style -> heading level, table cell / row marks)
come from the PAPX FKPs and inline pictures from the CHPX FKPs (``sprmCPicLocation``
-> PICF in the ``Data`` stream -> OfficeArt BLIP). Every lookup is optional: when
the property tables are missing or damaged the text is still converted with
heuristics. Word 6/95 files get a best-effort 8-bit text path.

Kingsoft WPS Writer ``.wps`` files are Word-binary compatible (``WordDocument``
stream). Microsoft Works ``.wps`` (``CONTENTS`` stream) only gets a best-effort
extraction of readable text runs.

The block model and chapter builder at the bottom are shared with :mod:`.hwp`.
"""

