# ================================================================ shared block model (also used by .hwp)

@dataclass(slots=True)
class ImageRef:
    """An inline image inside a paragraph (``name`` is a registered resource name)."""

    name: str


Parts = list  # list[str | ImageRef]


@dataclass(slots=True)
class Block:
    kind: str  # "p" | "h" | "table" | "img"
    parts: Parts = field(default_factory=list)
    level: int = 0
    rows: list = field(default_factory=list)  # table: rows -> cells -> paragraphs (Parts)
    toc: bool = False  # paragraph generated by a TOC field: never a chapter heading


def parts_text(parts: Parts) -> str:
    return "".join(part for part in parts if isinstance(part, str))


def parts_have_content(parts: Parts) -> bool:
    return any(isinstance(part, ImageRef) or part.strip() for part in parts)


def _render_parts(parts: Parts) -> str:
    out: list[str] = []
    for part in parts:
        if isinstance(part, ImageRef):
            out.append(f'<img src="{escape(part.name)}" alt=""/>')
        else:
            out.append(escape(part.replace("\t", " ")).replace("\n", "<br/>"))
    return "".join(out).strip()


def _strip_parts(parts: Parts) -> Parts:
    parts = list(parts)
    while parts and isinstance(parts[0], str) and not parts[0].strip():
        parts.pop(0)
    while parts and isinstance(parts[-1], str) and not parts[-1].strip():
        parts.pop()
    if parts and isinstance(parts[0], str):
        parts[0] = parts[0].lstrip()
    if parts and isinstance(parts[-1], str):
        parts[-1] = parts[-1].rstrip()
    return parts


def _render_block(block: Block, split_level: int | None) -> str:
    if block.kind == "table":
        rows = []
        for row in block.rows:
            cells = []
            for cell in row:
                body = "<br/>".join(_render_parts(_strip_parts(p)) for p in cell if parts_have_content(p))
                cells.append(f"<td>{body}</td>")
            if cells:
                rows.append(f"<tr>{''.join(cells)}</tr>")
        return f"<table><tbody>{''.join(rows)}</tbody></table>" if rows else ""
    if block.kind == "img":
        return f'<div class="image">{_render_parts(block.parts)}</div>'
    body = _render_parts(_strip_parts(block.parts))
    if not body:
        return ""
    if block.kind == "h":
        if split_level is None:
            tag = f"h{min(6, max(1, block.level + 1))}"
        elif block.level < split_level:
            tag = "h1"
        else:
            tag = f"h{min(6, block.level - split_level + 2)}"
        return f"<{tag}>{body}</{tag}>"
    return f"<p>{body}</p>"


def _heading_title(block: Block) -> str:
    return " ".join(parts_text(block.parts).split())[:300]


def build_chapters(blocks: list[Block], document: Document, max_heading_len: int = 80) -> list[Chapter]:
    """Group blocks into chapters at style headings, or at heading-like paragraphs when none exist.

    Chapter titles are not repeated in the body (same convention as ``split_text_chapters``);
    deeper headings become <h3>.. inside the body, shallower ones (a document title) <h1>.
    """
    names = {resource.name for resource in document.resources}

    def pick_level(found: list[Block]) -> int | None:
        if not found:
            return None
        counts = Counter(block.level for block in found)
        levels = sorted(counts)
        level = levels[0]
        if counts[level] == 1 and len(levels) > 1 and counts[levels[1]] >= 2:
            level = levels[1]  # a single top heading is the document title, not a chapter
        return level if counts[level] < MAX_CHAPTERS else None

    headings = [block for block in blocks if block.kind == "h"]
    split_level = pick_level(headings)
    if split_level is None or sum(block.level == split_level for block in headings) < 2:
        # No (useful) style headings: look for heading-like paragraphs ("Chương 1", "第一章", ...).
        regex_level = max((block.level for block in headings), default=0) + 1
        candidates = []
        for block in blocks:
            if block.kind != "p" or block.toc or any(isinstance(part, ImageRef) for part in block.parts):
                continue
            text = parts_text(block.parts).strip()
            if text and "\n" not in text and len(text) <= max_heading_len and CHAPTER_HEADING.match(text):
                candidates.append(block)
        if candidates and (not headings or len(candidates) >= 2) and len(candidates) < MAX_CHAPTERS:
            for block in candidates:
                block.kind, block.level = "h", regex_level
            split_level = regex_level
    sections: list[tuple[str, list[str]]] = []
    title, body = "", []
    for block in blocks:
        if split_level is not None and block.kind == "h" and block.level == split_level:
            if title or body:
                sections.append((title, body))
            title, body = _heading_title(block), []
            continue
        markup = _render_block(block, split_level)
        if markup:
            body.append(markup)
    if title or body:
        sections.append((title, body))
    chapters: list[Chapter] = []
    for index, (heading, parts) in enumerate(sections, 1):
        if not heading:
            heading = document.title if (document.title and index == 1) else f"Phần {index}"
        markup = sanitize_fragment("".join(parts), resolve_src=lambda src: src if src in names else "")
        chapters.append(Chapter(heading, markup))
    return chapters


class BlockBuilder:
    """Collects paragraphs into blocks, grouping table cells and rows."""

    def __init__(self) -> None:
        self.blocks: list[Block] = []
        self.rows: list[list[list[Parts]]] = []
        self.row: list[list[Parts]] = []
        self.cell: list[Parts] = []
        self.last_cell_end = False

    # table plumbing
    def add_to_cell(self, parts: Parts) -> None:
        self.cell.append(parts)

    def end_cell(self) -> None:
        self.row.append(self.cell)
        self.cell = []

    def end_row(self) -> None:
        if self.cell:
            self.end_cell()
        if self.row:
            self.rows.append(self.row)
        self.row = []

    def close_table(self) -> None:
        if self.cell:
            self.end_cell()
        if self.row:
            self.end_row()
        if self.rows:
            self.blocks.append(Block("table", rows=self.rows))
        self.rows, self.row, self.cell = [], [], []
        self.last_cell_end = False

    def add_table(self, rows: list[list[list[Parts]]]) -> None:
        self.close_table()
        rows = [row for row in rows if row]
        if rows:
            self.blocks.append(Block("table", rows=rows))

    # body
    def body(self, parts: Parts, level: int | None = None, toc: bool = False) -> None:
        self.close_table()
        if not parts_have_content(parts):
            return
        if level is not None and parts_text(parts).strip():
            self.blocks.append(Block("h", parts, level=level))
        else:
            self.blocks.append(Block("p", parts, toc=toc))

    def image(self, name: str) -> None:
        self.close_table()
        self.blocks.append(Block("img", [ImageRef(name)]))

    def finish(self) -> list[Block]:
        self.close_table()
        return self.blocks


# ================================================================ Word binary

_CP1252_FIX = {i: ord(bytes([i]).decode("cp1252", errors="ignore") or chr(i)) for i in range(0x80, 0xA0)}


def _decode_compressed(raw: bytes) -> str:
    """Word "compressed" 8-bit text: cp1252, undefined bytes kept as Latin-1."""
    return raw.decode("latin-1").translate(_CP1252_FIX)


_LID_CODEPAGE = {
    0x0404: "cp950", 0x0C04: "cp950", 0x1404: "cp950", 0x0804: "gbk", 0x1004: "gbk", 0x0411: "cp932",
    0x0412: "cp949", 0x042A: "cp1258", 0x0419: "cp1251", 0x0422: "cp1251", 0x0423: "cp1251", 0x0402: "cp1251",
    0x0C1A: "cp1251", 0x042F: "cp1251", 0x0408: "cp1253", 0x041F: "cp1254", 0x040D: "cp1255", 0x0401: "cp1256",
    0x0425: "cp1257", 0x0426: "cp1257", 0x0427: "cp1257", 0x041E: "cp874", 0x0405: "cp1250", 0x0415: "cp1250",
    0x040E: "cp1250", 0x041B: "cp1250", 0x0424: "cp1250", 0x041A: "cp1250", 0x0418: "cp1250", 0x041C: "cp1250",
}


@dataclass(slots=True)
class _Fib:
    nfib: int
    flags: int
    lid: int
    ccp_text: int
    word97: bool
    fc_lcb_pairs: list[tuple[int, int]]
    fc_min: int = 0
    fc_mac: int = 0

    @property
    def complex(self) -> bool:
        return bool(self.flags & 0x0004)

    @property
    def encrypted(self) -> bool:
        return bool(self.flags & 0x0100)

    @property
    def table_stream(self) -> str:
        return "1Table" if self.flags & 0x0200 else "0Table"

    def fc_lcb(self, index: int) -> tuple[int, int]:
        return self.fc_lcb_pairs[index] if index < len(self.fc_lcb_pairs) else (0, 0)


def _u16(data: bytes, offset: int) -> int:
    return struct.unpack_from("<H", data, offset)[0]


def _u32(data: bytes, offset: int) -> int:
    return struct.unpack_from("<I", data, offset)[0]


def _parse_fib(wd: bytes) -> _Fib:
    if len(wd) < 0x40:
        raise FormatError("truncated Word document header")
    ident, nfib = struct.unpack_from("<HH", wd, 0)
    if ident != 0xA5EC:
        if ident in (0xA5DB, 0xA5DC):
            raise FormatError("Word 2.0 documents are not supported")
        raise FormatError("invalid Word document header")
    lid, _pn_next, flags = struct.unpack_from("<HHH", wd, 0x06)
    if nfib < 0x65:
        raise FormatError("Word 2.0 documents are not supported")
    if nfib < 0xC0:  # Word 6.0 / Word 95: fixed FIB layout, everything in the WordDocument stream
        if len(wd) < 0x168:
            raise FormatError("truncated Word 6/95 document header")
        fc_min, fc_mac = struct.unpack_from("<II", wd, 0x18)
        ccp_text = _u32(wd, 0x34)
        pairs = [struct.unpack_from("<II", wd, 0x58 + 8 * index) for index in range(34)]
        return _Fib(nfib, flags, lid, ccp_text, False, pairs, fc_min, fc_mac)
    pos = 32
    csw = _u16(wd, pos)
    pos += 2 + csw * 2
    if pos + 2 > len(wd):
        raise FormatError("truncated Word document header")
    cslw = _u16(wd, pos)
    rglw = pos + 2
    pos = rglw + cslw * 4
    if cslw < 4 or pos + 2 > len(wd):
        raise FormatError("truncated Word document header")
    ccp_text = _u32(wd, rglw + 12)
    count = _u16(wd, pos)
    base = pos + 2
    count = min(count, max(0, (len(wd) - base) // 8))
    pairs = [struct.unpack_from("<II", wd, base + 8 * index) for index in range(count)]
    if len(pairs) <= 33:
        raise FormatError("truncated Word document header")
    return _Fib(nfib, flags, lid, ccp_text, True, pairs)


@dataclass(slots=True)
class _Piece:
    cp_start: int
    cp_end: int
    byte_start: int
    compressed: bool


def _parse_clx(clx: bytes) -> list[tuple[int, int, int]]:
    """(cp_start, cp_end, raw fc) for every piece of the CLX's PlcPcd."""
    pos = 0
    for _ in range(1 << 16):
        if pos >= len(clx) or clx[pos] != 0x01:
            break
        if pos + 3 > len(clx):
            raise FormatError("corrupt piece table")
        size = struct.unpack_from("<h", clx, pos + 1)[0]
        if size < 0:
            raise FormatError("corrupt piece table")
        pos += 3 + size
    if pos + 5 > len(clx) or clx[pos] != 0x02:
        raise FormatError("corrupt piece table")
    lcb = _u32(clx, pos + 1)
    plc = clx[pos + 5:pos + 5 + lcb]
    if lcb < 16 or len(plc) < lcb:
        raise FormatError("corrupt piece table")
    count = (lcb - 4) // 12
    if count > MAX_PIECES:
        raise FormatError("piece table is too large")
    cps = struct.unpack_from(f"<{count + 1}I", plc, 0)
    pieces: list[tuple[int, int, int]] = []
    for index in range(count):
        start, end = cps[index], cps[index + 1]
        if end < start:
            raise FormatError("corrupt piece table")
        fc = _u32(plc, 4 * (count + 1) + 8 * index + 2)
        pieces.append((start, end, fc))
    return pieces


def _word_text(wd: bytes, table: bytes, fib: _Fib) -> tuple[str, list[_Piece], int]:
    """(main document text, pieces, cp of text[0])."""
    fc_clx, lcb_clx = fib.fc_lcb(33)
    source = table if fib.word97 else wd
    if not fib.word97 and (not fib.complex or not lcb_clx):
        if fib.fc_min >= len(wd):
            raise FormatError("corrupt Word 6/95 document")
        length = fib.ccp_text or max(0, fib.fc_mac - fib.fc_min)
        raw = wd[fib.fc_min:fib.fc_min + min(length, MAX_TEXT_CHARS)]
        codec = _LID_CODEPAGE.get(fib.lid, "cp1252")
        return raw.decode(codec, errors="replace"), [], 0
    if not lcb_clx or fc_clx + lcb_clx > len(source):
        raise FormatError("Word document has no readable piece table")
    raw_pieces = _parse_clx(source[fc_clx:fc_clx + lcb_clx])
    if not raw_pieces:
        raise FormatError("Word document has no text")
    cp_base = raw_pieces[0][0]
    last_cp = raw_pieces[-1][1]
    limit = cp_base + fib.ccp_text if 0 < fib.ccp_text <= last_cp - cp_base else last_cp
    limit = min(limit, cp_base + MAX_TEXT_CHARS)
    codec95 = _LID_CODEPAGE.get(fib.lid, "cp1252")
    texts: list[str] = []
    pieces: list[_Piece] = []
    for start, end, fc in raw_pieces:
        if start >= limit:
            break
        count = min(end, limit) - start
        if fib.word97:
            compressed = bool(fc & 0x40000000)
            value = fc & 0x3FFFFFFF
            byte_start = value // 2 if compressed else value
        else:
            compressed, byte_start = True, fc
        pieces.append(_Piece(start, end, byte_start, compressed))
        if compressed:
            raw = wd[byte_start:byte_start + count] if byte_start < len(wd) else b""
            text = _decode_compressed(raw) if fib.word97 else raw.decode(codec95, errors="replace")
        else:
            raw = wd[byte_start:byte_start + 2 * count] if byte_start < len(wd) else b""
            text = raw[: len(raw) - len(raw) % 2].decode("utf-16-le", errors="replace")
        if len(text) < count:  # truncated piece: pad so that string index == CP
            text += " " * (count - len(text))
        texts.append(text[:count])
    return "".join(texts), pieces, cp_base


# ---------------------------------------------------------------- property tables (Word 97+)

@dataclass(slots=True)
class _Para:
    level: int | None
    in_table: bool
    ttp: bool
    itap: int
    inner_ttp: bool


def _iter_sprms(grpprl: bytes):
    """(sprm, operand) pairs of a Word 97 grpprl; stops quietly at the first malformed sprm."""
    pos, size_total = 0, len(grpprl)
    while pos + 2 <= size_total:
        sprm = grpprl[pos] | (grpprl[pos + 1] << 8)
        pos += 2
        spra = sprm >> 13
        if spra in (0, 1):
            size = 1
        elif spra in (2, 4, 5):
            size = 2
        elif spra == 3:
            size = 4
        elif spra == 7:
            size = 3
        elif sprm in (0xD608, 0xD606):  # sprmTDefTable: 2-byte cb, remainder is cb - 1 bytes
            if pos + 2 > size_total:
                return
            size = (grpprl[pos] | (grpprl[pos + 1] << 8)) + 1
        elif sprm == 0xC615 and pos < size_total and grpprl[pos] == 255:  # sprmPChgTabs, long form
            cursor = pos + 1
            if cursor >= size_total:
                return
            cursor += 1 + 4 * grpprl[cursor]
            if cursor >= size_total:
                return
            cursor += 1 + 3 * grpprl[cursor]
            size = cursor - pos
        else:
            if pos >= size_total:
                return
            size = grpprl[pos] + 1
        if pos + size > size_total:
            return
        yield sprm, grpprl[pos:pos + size]
        pos += size


def _plcf_bte(table: bytes, fc: int, lcb: int) -> tuple[tuple[int, ...], tuple[int, ...]] | None:
    if lcb < 12 or (lcb - 4) % 8 or fc + lcb > len(table):
        return None
    count = (lcb - 4) // 8
    if count > MAX_BTE_ENTRIES:
        return None
    fcs = struct.unpack_from(f"<{count + 1}I", table, fc)
    pns = struct.unpack_from(f"<{count}I", table, fc + 4 * (count + 1))
    return fcs, tuple(pn & 0x3FFFFF for pn in pns)


_HEADING_NAME = re.compile(
    r"^(?:heading|überschrift|titre|título|titolo|заголовок|标题|標題|見出し|제목|개요|tiêu đề|tieu de|kop)\s*(\d)$",
    re.IGNORECASE,
)


def _style_levels(table: bytes, fc: int, lcb: int) -> dict[int, int]:
    """istd -> heading level (1-9 for Heading 1-9, 0 for Title) from the STSH."""
    levels: dict[int, int] = {}
    if lcb < 4 or fc + lcb > len(table):
        return {istd: istd for istd in range(1, 10)}
    blob = table[fc:fc + lcb]
    cb_stshi = _u16(blob, 0)
    if cb_stshi < 4 or 2 + cb_stshi > len(blob):
        return {istd: istd for istd in range(1, 10)}
    cstd, cb_base = _u16(blob, 2), _u16(blob, 4)
    pos = 2 + cb_stshi
    for istd in range(min(cstd, 4096)):
        if pos + 2 > len(blob):
            break
        cb_std = _u16(blob, pos)
        pos += 2
        std = blob[pos:pos + cb_std]
        pos += cb_std
        if len(std) < 2:
            continue
        sti = _u16(std, 0) & 0x0FFF
        if 1 <= sti <= 9:
            levels[istd] = sti
        elif sti == 62:  # Title
            levels[istd] = 0
        elif sti == 0x0FFE and cb_base and len(std) >= cb_base + 2:
            cch = _u16(std, cb_base)
            name = std[cb_base + 2:cb_base + 2 + 2 * min(cch, 120)].decode("utf-16-le", errors="replace")
            match = _HEADING_NAME.match(name.strip())
            if match and match.group(1) != "0":
                levels[istd] = int(match.group(1))
    return levels


class _Properties:
    """Paragraph / character property lookups by CP (all failures are soft: ``None``)."""

    def __init__(self, wd: bytes, table: bytes, fib: _Fib, pieces: list[_Piece]) -> None:
        self.wd = wd
        self.pieces = pieces
        self.piece_starts = [piece.cp_start for piece in pieces]
        self.papx = _plcf_bte(table, *fib.fc_lcb(13))
        self.chpx = _plcf_bte(table, *fib.fc_lcb(12))
        self.levels = _style_levels(table, *fib.fc_lcb(1))
        self._papx_pages: dict[int, list[tuple[int, int, int, bytes]]] = {}
        self._chpx_pages: dict[int, list[tuple[int, int, bytes]]] = {}

    def _fc(self, cp: int) -> int | None:
        index = bisect_right(self.piece_starts, cp) - 1
        if index < 0:
            return None
        piece = self.pieces[index]
        if cp >= piece.cp_end:
            return None
        return piece.byte_start + (cp - piece.cp_start) * (1 if piece.compressed else 2)

    def _page(self, bte, fc: int) -> int | None:
        fcs, pns = bte
        index = bisect_right(fcs, fc) - 1
        if index < 0 or index >= len(pns) or fc >= fcs[index + 1]:
            return None
        pn = pns[index]
        return pn if (pn + 1) * 512 <= len(self.wd) else None

    def _papx_runs(self, pn: int) -> list[tuple[int, int, int, bytes]]:
        runs = self._papx_pages.get(pn)
        if runs is not None:
            return runs
        runs = []
        page = self.wd[pn * 512:pn * 512 + 512]
        crun = page[511]
        if crun and 4 * (crun + 1) + 13 * crun <= 511:
            fcs = struct.unpack_from(f"<{crun + 1}I", page, 0)
            for index in range(crun):
                offset = page[4 * (crun + 1) + 13 * index] * 2
                istd, grpprl = 0, b""
                if offset and offset < 511:
                    cb = page[offset]
                    if cb == 0 and offset + 1 < 511:
                        start, size = offset + 2, 2 * page[offset + 1]
                    else:
                        start, size = offset + 1, 2 * cb - 1
                    blob = page[start:min(start + size, 511)]
                    if len(blob) >= 2:
                        istd, grpprl = _u16(blob, 0), blob[2:]
                runs.append((fcs[index], fcs[index + 1], istd, grpprl))
        self._papx_pages[pn] = runs
        return runs

    def _chpx_runs(self, pn: int) -> list[tuple[int, int, bytes]]:
        runs = self._chpx_pages.get(pn)
        if runs is not None:
            return runs
        runs = []
        page = self.wd[pn * 512:pn * 512 + 512]
        crun = page[511]
        if crun and 5 * crun + 4 <= 511:
            fcs = struct.unpack_from(f"<{crun + 1}I", page, 0)
            for index in range(crun):
                offset = page[4 * (crun + 1) + index] * 2
                grpprl = b""
                if offset and offset < 511:
                    grpprl = page[offset + 1:min(offset + 1 + page[offset], 511)]
                runs.append((fcs[index], fcs[index + 1], grpprl))
        self._chpx_pages[pn] = runs
        return runs

    @staticmethod
    def _run_at(runs, fc: int):
        for run in runs:
            if run[0] <= fc < run[1]:
                return run
        return None

    def para(self, cp: int) -> _Para | None:
        if self.papx is None:
            return None
        fc = self._fc(cp)
        pn = self._page(self.papx, fc) if fc is not None else None
        if pn is None:
            return None
        run = self._run_at(self._papx_runs(pn), fc)
        if run is None:
            return None
        istd, in_table, ttp, inner_ttp, itap, outline = run[2], False, False, False, None, None
        for sprm, operand in _iter_sprms(run[3]):
            if sprm == 0x2416:
                in_table = bool(operand[0])
            elif sprm == 0x2417:
                ttp = bool(operand[0])
            elif sprm == 0x244C:
                inner_ttp = bool(operand[0])
            elif sprm == 0x244B and operand[0]:
                itap = max(itap or 0, 2)
            elif sprm == 0x6649:
                itap = struct.unpack("<i", operand)[0]
            elif sprm == 0x2640:
                outline = operand[0]
            elif sprm == 0x4600:
                istd = _u16(operand, 0)
        if itap is None:
            itap = 1 if in_table else 0
        level = self.levels.get(istd)
        if outline is not None:
            level = outline + 1 if outline < 9 else None
        return _Para(level, in_table or itap > 0, ttp, max(0, min(itap, 64)), inner_ttp)

    def picture_location(self, cp: int) -> int | None:
        if self.chpx is None:
            return None
        fc = self._fc(cp)
        pn = self._page(self.chpx, fc) if fc is not None else None
        if pn is None:
            return None
        run = self._run_at(self._chpx_runs(pn), fc)
        if run is None:
            return None
        location, is_object = None, False
        for sprm, operand in _iter_sprms(run[2]):
            if sprm == 0x6A03:
                location = _u32(operand, 0)
            elif sprm in (0x0806, 0x080A) and operand[0]:  # fData (form field) / fOle2 (OLE object)
                is_object = True
        return None if is_object else location

    def deleted_ranges(self) -> list[tuple[int, int]]:
        """CP ranges of tracked-deleted text (sprmCFRMarkDel), which is still stored in the pieces."""
        if self.chpx is None:
            return []
        deleted: list[tuple[int, int]] = []
        for pn in sorted(set(self.chpx[1]))[: len(self.wd) // 512]:
            if (pn + 1) * 512 > len(self.wd):
                continue
            for fc_start, fc_end, grpprl in self._chpx_runs(pn):
                if fc_end > fc_start and any(sprm == 0x0800 and operand[0] for sprm, operand in _iter_sprms(grpprl)):
                    deleted.append((fc_start, fc_end))
        if not deleted:
            return []
        deleted.sort()
        starts = [start for start, _ in deleted]
        ranges: list[tuple[int, int]] = []
        for piece in self.pieces:
            width = 1 if piece.compressed else 2
            low, high = piece.byte_start, piece.byte_start + (piece.cp_end - piece.cp_start) * width
            index = max(0, bisect_right(starts, low) - 1)
            while index < len(deleted) and deleted[index][0] < high:
                start, end = max(deleted[index][0], low), min(deleted[index][1], high)
                if start < end:
                    ranges.append((piece.cp_start + (start - low) // width,
                                   piece.cp_start + (end - low + width - 1) // width))
                index += 1
        return ranges


def _remove_ranges(text: str, cp_base: int, ranges: list[tuple[int, int]]) -> str:
    """Blank out CP ranges with NULs (dropped later) so that string index == CP still holds."""
    if not ranges:
        return text
    chars = list(text)
    for start, end in ranges:
        start, end = max(0, start - cp_base), min(len(chars), end - cp_base)
        if start < end:
            chars[start:end] = "\0" * (end - start)
    return "".join(chars)


# ---------------------------------------------------------------- inline pictures (PICF + OfficeArt BLIP)

def _dib_to_bmp(dib: bytes) -> bytes:
    if len(dib) < 16:
        return b""
    header_size = _u32(dib, 0)
    if header_size == 12:
        bit_count = _u16(dib, 10)
        palette = 3 * (1 << bit_count) if bit_count <= 8 else 0
    elif 40 <= header_size <= len(dib) and header_size <= 256:
        bit_count, compression = _u16(dib, 14), _u32(dib, 16)
        used = _u32(dib, 32)
        colors = used if 0 < used <= 256 else (1 << bit_count if bit_count <= 8 else 0)
        palette = 4 * colors + (12 if compression == 3 and header_size == 40 else 0)
    else:
        return b""
    offset = 14 + header_size + palette
    return b"BM" + struct.pack("<IHHI", 14 + len(dib), 0, 0, offset) + dib


_BLIP_TWO_UIDS = {0xF01D: {0x46B, 0x6E3}, 0xF02A: {0x46B, 0x6E3}, 0xF01E: {0x6E1}, 0xF01F: {0x7A9}}


def _find_blip(buf: bytes, pos: int, end: int, depth: int = 0) -> bytes:
    for _ in range(4096):
        if pos + 8 > end:
            break
        ver_inst, rec_type, rec_len = struct.unpack_from("<HHI", buf, pos)
        body = pos + 8
        rec_end = min(end, body + rec_len)
        if rec_type == 0xF007 and rec_end - body >= 36:  # OfficeArtFBSE wrapping the BLIP
            found = _find_blip(buf, body + 36 + buf[body + 33], rec_end, depth + 1) if depth < 8 else b""
            if found:
                return found
        elif rec_type in _BLIP_TWO_UIDS:
            inst = ver_inst >> 4
            start = body + (32 if inst in _BLIP_TWO_UIDS[rec_type] else 16) + 1
            payload = buf[start:rec_end]
            if rec_type == 0xF01F:
                payload = _dib_to_bmp(payload)
            if payload and sniff_image_type(payload) not in ("", "image/svg+xml"):
                return payload
        elif (ver_inst & 0xF) == 0xF and depth < 8:  # container record
            found = _find_blip(buf, body, rec_end, depth + 1)
            if found:
                return found
        pos = body + rec_len
    return b""


def _picture_at(data: bytes, offset: int) -> bytes:
    if offset + 0x44 > len(data):
        return b""
    lcb, cb_header = struct.unpack_from("<IH", data, offset)
    if cb_header < 0x44 or lcb <= cb_header:
        return b""
    end = min(len(data), offset + lcb)
    if end - offset > MAX_IMAGE_BYTES + 4096:
        return b""
    pos = offset + cb_header
    if _u16(data, offset + 6) == 0x66 and pos < end:  # MM_SHAPEFILE: a picture name precedes the data
        pos += 1 + data[pos]
    return _find_blip(data, pos, end)


# ---------------------------------------------------------------- text -> blocks

_TOKEN = re.compile(r"[\x00-\x1f]|[^\x00-\x1f]+")


@dataclass(slots=True)
class _Field:
    result: bool = False
    toc: bool = False
    instruction: list[str] = field(default_factory=list)


def _word_blocks(text: str, cp_base: int, props: _Properties | None, picture) -> list[Block]:
    builder = BlockBuilder()
    stack: list[_Field] = []
    hidden = 0  # open fields still in their instruction part
    toc_open = 0
    parts: Parts = []
    para_toc = False

    def end_paragraph(cp: int, terminator: str) -> None:
        nonlocal parts, para_toc
        info = None
        if props is not None:
            try:
                info = props.para(cp)
            except (struct.error, IndexError, ValueError):
                info = None
        current, parts = parts, []
        toc, para_toc = para_toc or bool(toc_open), False
        if info is not None:
            builder.last_cell_end = False
            if terminator == "\x07" and info.itap <= 1:
                if info.ttp:
                    builder.end_row()
                else:
                    builder.add_to_cell(current)
                    builder.end_cell()
                return
            if info.in_table:
                if not info.inner_ttp:
                    builder.add_to_cell(current)
                return
            builder.body(current, info.level, toc)
            return
        # heuristics when paragraph properties are unavailable
        if terminator == "\x07":
            if builder.last_cell_end and builder.row and not parts_have_content(current):
                builder.end_row()
                builder.last_cell_end = False
            else:
                builder.add_to_cell(current)
                builder.end_cell()
                builder.last_cell_end = True
            return
        builder.last_cell_end = False
        if builder.row:
            builder.add_to_cell(current)
            return
        builder.body(current, None, toc)

    for match in _TOKEN.finditer(text):
        token = match.group()
        code = ord(token[0])
        if code >= 0x20:
            if hidden:
                top = stack[-1]
                if not top.result and sum(len(item) for item in top.instruction) < 512:
                    top.instruction.append(token)
                continue
            parts.append(token)
            if toc_open:
                para_toc = True
            continue
        cp = cp_base + match.start()
        if code == 0x13:
            if len(stack) < MAX_FIELD_DEPTH:
                stack.append(_Field())
                hidden += 1
        elif code == 0x14:
            if stack and not stack[-1].result:
                top = stack[-1]
                top.result = True
                hidden -= 1
                top.toc = "".join(top.instruction).strip().upper().startswith("TOC")
                toc_open += top.toc
        elif code == 0x15:
            if stack:
                top = stack.pop()
                if not top.result:
                    hidden -= 1
                elif top.toc:
                    toc_open -= 1
        elif code in (0x0D, 0x07, 0x0C):
            end_paragraph(cp, token)
        elif hidden:
            continue
        elif code == 0x0B:
            parts.append("\n")
        elif code == 0x09:
            parts.append("\t")
        elif code == 0x1E:
            parts.append("‑")
        elif code == 0x01 and picture is not None:
            name = picture(cp)
            if name:
                parts.append(ImageRef(name))
        # 0x1F optional hyphen, 0x08 drawn object, 0x02 / 0x05 note marks, other controls: dropped
    if parts:
        end_paragraph(cp_base + len(text), "\r")
    return builder.finish()


def _clean_title(title: str) -> str:
    title = re.sub(r"^Microsoft Word\s*-\s*", "", title, flags=re.IGNORECASE)
    title = re.sub(r"\.(?:docx?|dot|wps|rtf)$", "", title, flags=re.IGNORECASE)
    return title.strip()


def _convert_word(cfb: CompoundFile) -> Document:
    wd = cfb.read("WordDocument", limit=WORD_STREAM_LIMIT)
    fib = _parse_fib(wd)
    if fib.encrypted:
        raise FormatError("encrypted document")
    table = b""
    if fib.word97:
        name = fib.table_stream
        if not cfb.is_stream(name):
            raise FormatError(f"Word document has no {name} stream")
        table = cfb.read(name, limit=TABLE_STREAM_LIMIT)
    text, pieces, cp_base = _word_text(wd, table, fib)
    document = Document()
    title, authors = summary_title_author(cfb)
    document.title, document.authors = _clean_title(title), authors
    props = None
    if fib.word97 and pieces:
        try:
            props = _Properties(wd, table, fib, pieces)
        except (struct.error, IndexError, ValueError):
            props = None
    if props is not None:
        try:
            text = _remove_ranges(text, cp_base, props.deleted_ranges())
        except (struct.error, IndexError, ValueError):
            pass
    picture = None
    if props is not None and props.chpx is not None and cfb.is_stream("Data"):
        cache: dict[int, str] = {}
        state: dict[str, bytes | None] = {"data": None}

        def picture(cp: int) -> str:
            try:
                offset = props.picture_location(cp)
                if offset is None:
                    return ""
                if offset in cache:
                    return cache[offset]
                if state["data"] is None:
                    state["data"] = cfb.read("Data", limit=DATA_STREAM_LIMIT)
                image = _picture_at(state["data"], offset)
                name = ""
                if image:
                    name = document.add_resource(image, sniff_image_type(image), "image")
                cache[offset] = name
                return name
            except (FormatError, struct.error, IndexError, ValueError):
                return ""

    blocks = _word_blocks(text, cp_base, props, picture)
    if not document.title:
        titles = [block for block in blocks if block.kind == "h" and block.level == 0]
        if titles:
            document.title = _heading_title(titles[0])
    document.chapters = build_chapters(blocks, document)
    if not document.chapters:
        raise FormatError("document has no readable text")
    return document


# ================================================================ Microsoft Works

_WORKS_UTF16_RUN = re.compile(
    "[\t\n\r\x20-\x7e -ɏͰ-ϿЀ-ӿḀ-ỿ‐-‧‰-›€]{20,}"
)
_WORKS_ANSI_RUN = re.compile(rb"[\t\n\r\x20-\x7e\x80-\xff]{40,}")


def _works_text(raw: bytes) -> str:
    best: list[str] = []
    for align in (0, 1):
        chunk = raw[align:]
        decoded = chunk[: len(chunk) - len(chunk) % 2].decode("utf-16-le", errors="replace")
        runs = [run for run in _WORKS_UTF16_RUN.findall(decoded) if sum(ch.isalpha() for ch in run) >= len(run) // 3]
        if sum(map(len, runs)) > sum(map(len, best)):
            best = runs
    if not best:  # Works 4.x: 8-bit text
        for run in _WORKS_ANSI_RUN.findall(raw):
            text = _decode_compressed(run)
            letters = sum(ch.isalpha() or ch == " " for ch in text)
            if letters >= len(text) * 0.75 and " " in text:
                best.append(text)
    return "\n".join(best)


def _convert_works(cfb: CompoundFile) -> Document:
    raw = cfb.read("CONTENTS", limit=TABLE_STREAM_LIMIT)
    text = _works_text(raw).replace("\r\n", "\n").replace("\r", "\n")
    if len(text.strip()) < 20:
        raise FormatError("Microsoft Works .wps is not supported")
    document = Document(source_format="wps")
    title, authors = summary_title_author(cfb)
    document.title, document.authors = _clean_title(title), authors
    builder = BlockBuilder()
    for line in text.split("\n"):
        builder.body([line])
    document.chapters = build_chapters(builder.finish(), document)
    if not document.chapters:
        raise FormatError("Microsoft Works .wps is not supported")
    return document


# ================================================================ entry point

def _check_real_type(data: bytes) -> None:
    """Safety net for files whose extension lies (the registry sniffs most of these first)."""
    if data.startswith(MAGIC):
        return
    head = data[:4096]
    text_head = head.lstrip(b"\xef\xbb\xbf \r\n\t\0")
    lowered = text_head[:2048].lower()
    if text_head.startswith(b"{\\rtf"):
        raise FormatError("file is RTF, not a Word binary document")
    if head.startswith(b"PK\x03\x04") or head.startswith(b"PK\x05\x06"):
        raise FormatError("file is a ZIP-based document (DOCX/ODT), not a Word binary document")
    if lowered.startswith(b"<"):
        if b"w:worddocument" in lowered or b"mso-application" in lowered:
            raise FormatError("file is Word 2003 XML, not a Word binary document")
        raise FormatError("file is HTML/XML, not a Word binary document")
    if lowered.startswith(b"mime-version:") or b"multipart/related" in lowered[:512]:
        raise FormatError("file is MHTML (web archive), not a Word binary document")
    if head[:2] in (b"\xdb\xa5", b"\xdc\xa5"):
        raise FormatError("Word 2.0 documents are not supported")
    if head[:4] in (b"\x31\xbe\x00\x00", b"\x32\xbe\x00\x00"):
        raise FormatError("Word for DOS / Windows Write documents are not supported")
    if head[:2] in (b"\xff\xfe", b"\xfe\xff") or (head and b"\0" not in head and
                                                   sum(byte < 9 or 13 < byte < 32 for byte in head) == 0):
        raise FormatError("file is plain text, not a Word binary document")
    raise FormatError("not a Word binary document")


def convert(path: Path) -> Document:
    data = read_limited(path)
    _check_real_type(data)
    cfb = CompoundFile(data)
    ext = Path(path).suffix.lower().lstrip(".")
    if cfb.is_stream("WordDocument"):
        document = _convert_word(cfb)
        document.source_format = ext if ext in {"doc", "dot", "wps"} else "doc"
        return document
    if cfb.is_stream("CONTENTS"):
        return _convert_works(cfb)
    if cfb.is_stream("EncryptedPackage"):
        raise FormatError("encrypted document")
    if cfb.is_stream("Workbook") or cfb.is_stream("Book"):
        raise FormatError("file is an Excel workbook, not a Word document")
    if cfb.is_stream("PowerPoint Document"):
        raise FormatError("file is a PowerPoint presentation, not a Word document")
    if cfb.is_stream("FileHeader") and cfb.exists("BodyText"):
        raise FormatError("file is a Hangul (HWP) document, not a Word document")
    raise FormatError("not a Word document (no WordDocument stream)")
